const dictionaries: Record<Language, Record<TranslationKey, string>> = { vi, en };

export function getTranslator(language: Language): (key: TranslationKey) => string {
  const dict = dictionaries[language] || dictionaries.vi;
  return (key: TranslationKey) => dict[key] ?? dictionaries.vi[key] ?? key;
}
